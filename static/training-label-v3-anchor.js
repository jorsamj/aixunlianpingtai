(() => {
  'use strict';
  if (window.__trainingLabelV3AnchorInstalled) return;
  window.__trainingLabelV3AnchorInstalled = true;

  let syncScheduled = false;
  let lastPanel = null;
  let lastStateSignature = '';

  function appState() {
    try {
      if (typeof state !== 'undefined') return state;
    } catch (_) {}
    return window.state || null;
  }

  function activeTrainingPanel() {
    const direct = document.querySelector('.train-v3-summary')?.closest('.train428-panel');
    if (direct) return direct;

    const legacySummary = document.querySelector('.train429-create .train429-data-summary:not(.training-label-v3-anchor)');
    if (legacySummary) return legacySummary.closest('.train428-panel') || legacySummary.parentElement;

    const roots = [...document.querySelectorAll('.train429-create .train428-panel')];
    return roots.find(panel => {
      const header = panel.querySelector('header');
      return /本次训练素材|训练数据/.test(String(header?.textContent || ''));
    }) || null;
  }

  function anchorPoint(panel) {
    return panel?.querySelector('.train-v3-summary')
      || panel?.querySelector('.train429-data-summary:not(.training-label-v3-anchor)')
      || panel?.querySelector('.train428-data')
      || panel?.querySelector('header')
      || null;
  }

  function stateSignature() {
    const s = appState();
    const ids = s?.train429Selected instanceof Set
      ? [...s.train429Selected].map(String).sort()
      : [];
    return JSON.stringify({
      algorithmId: String(s?.train428AlgorithmId || ''),
      ids,
    });
  }

  function sync() {
    const panel = activeTrainingPanel();
    if (!panel) {
      lastPanel = null;
      lastStateSignature = '';
      return false;
    }

    let createdAnchor = false;
    const existingSummary = panel.querySelector('.train429-data-summary:not(.training-label-v3-anchor)');
    if (!existingSummary) {
      let anchor = panel.querySelector(':scope > .training-label-v3-anchor');
      if (!anchor) {
        anchor = document.createElement('div');
        anchor.className = 'train429-data-summary training-label-v3-anchor';
        anchor.setAttribute('aria-hidden', 'true');
        anchor.style.display = 'none';
        const point = anchorPoint(panel);
        if (point) point.insertAdjacentElement('afterend', anchor);
        else panel.prepend(anchor);
        createdAnchor = true;
      }
    }

    const signature = stateSignature();
    const labelPanel = document.getElementById('trainingLabelContractPanel');
    const labelPanelMissing = !labelPanel || !panel.contains(labelPanel);
    const panelChanged = panel !== lastPanel;
    const stateChanged = signature !== lastStateSignature;

    lastPanel = panel;
    lastStateSignature = signature;

    // Critical: do not unconditionally refresh here. refresh() rewrites the label
    // panel DOM, which itself is observed. Refresh only for a real training-panel
    // or selection-state change so MutationObserver cannot self-trigger forever.
    if (createdAnchor || labelPanelMissing || panelChanged || stateChanged) {
      window.TrainingLabelRuntime?.refresh?.();
    }
    return true;
  }

  function isInternalMutation(record) {
    const target = record?.target;
    if (!(target instanceof Element)) return false;
    return Boolean(
      target.closest('#trainingLabelContractPanel')
      || target.closest('.training-label-v3-anchor')
    );
  }

  function scheduleSync(records = []) {
    // Ignore DOM churn generated by the label selector itself.
    if (records.length && records.every(isInternalMutation)) return;
    if (syncScheduled) return;
    syncScheduled = true;
    queueMicrotask(() => {
      syncScheduled = false;
      sync();
    });
  }

  const observer = typeof MutationObserver !== 'undefined'
    ? new MutationObserver(records => {
        if (activeTrainingPanel()) scheduleSync(records);
      })
    : null;
  observer?.observe(document.getElementById('modalBody') || document.body, {childList: true, subtree: true});

  sync();
  for (const delay of [0, 20, 80, 180, 400, 800, 1600]) setTimeout(sync, delay);

  window.TrainingLabelV3Anchor = {
    sync,
    build: '422507',
    destroy() { observer?.disconnect(); },
  };
})();
