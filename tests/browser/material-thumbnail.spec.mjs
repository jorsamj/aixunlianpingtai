import {test, expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';

test('real material thumbnail renders JPEG through the existing media owner and preserves original PNG',async({page},testInfo)=>{
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect.poll(()=>page.evaluate(()=>typeof state !== 'undefined' && state.uiReady && typeof window.materialMedia412==='function')).toBe(true);
  const pid=await page.evaluate(()=>state.project.id);
  const png=execFileSync('python',['-c',"from PIL import Image; import io,sys; b=io.BytesIO(); Image.new('RGB',(1200,800),'#4c8fae').save(b,format='PNG'); sys.stdout.buffer.write(b.getvalue())"]);
  const sourceSha=createHash('sha256').update(png).digest('hex');
  const filename='browser-real-thumbnail.png';
  const upload=await page.request.post(`/api/projects/${pid}/images`,{multipart:{dataset_id:'default',files:{name:filename,mimeType:'image/png',buffer:png}}});
  expect(upload.ok()).toBe(true);
  const uploaded=await upload.json();
  expect(uploaded.uploaded_count).toBe(1);
  const imageId=uploaded.uploaded[0].id;
  const listing=await page.request.get(`/api/v61/projects/${pid}/materials?page=1&page_size=20&query=${encodeURIComponent(filename)}`);
  expect(listing.ok()).toBe(true);
  const material=(await listing.json()).items.find(row=>row.id===imageId);
  expect(material).toBeTruthy();
  const originalUrl=`/api/v61/projects/${pid}/materials/${imageId}/content`;
  expect(material.url).toBe(originalUrl);
  expect(material.content_sha256).toBe(sourceSha);
  expect(material.thumbnail_url).toBe(originalUrl+'/thumbnail?edge=384');
  const before=await page.request.get(originalUrl);
  expect(before.status()).toBe(200);
  expect(createHash('sha256').update(await before.body()).digest('hex')).toBe(sourceSha);
  const thumbnailResponse=page.waitForResponse(response=>new URL(response.url()).pathname===originalUrl+'/thumbnail');
  await page.evaluate(row=>{
    const host=document.createElement('div');host.id='real-thumbnail-smoke';
    host.innerHTML=`<div class="data426-pic data411-pic" style="width:400px;height:300px">${window.materialMedia412(row,true)}</div>`;
    document.getElementById('view').replaceChildren(host);
  },material);
  const actual=await thumbnailResponse;
  expect(actual.status()).toBe(200);
  expect(actual.headers()['content-type']).toContain('image/jpeg');
  const jpeg=await actual.body();
  expect([...jpeg.subarray(0,2)]).toEqual([0xff,0xd8]);
  const image=page.locator('#real-thumbnail-smoke img');
  await expect(image).toBeVisible();
  await expect(image).toHaveAttribute('src',material.thumbnail_url);
  await expect(page.locator('#real-thumbnail-smoke .material-media412')).toHaveAttribute('data-image-state','ready');
  await expect.poll(()=>image.evaluate(node=>node.complete && node.naturalWidth)).toBe(384);
  expect(await image.evaluate(node=>node.naturalHeight)).toBe(256);
  const after=await page.request.get(material.url);
  expect(after.status()).toBe(200);
  expect(createHash('sha256').update(await after.body()).digest('hex')).toBe(sourceSha);
  const refreshed=await page.request.get(`/api/v61/projects/${pid}/materials?page=1&page_size=20&query=${encodeURIComponent(filename)}`);
  expect((await refreshed.json()).items.find(row=>row.id===imageId).url).toBe(originalUrl);
  expect(errors).toEqual([]);
  await page.locator('#real-thumbnail-smoke').screenshot({path:testInfo.outputPath('real-material-thumbnail.png')});
});
